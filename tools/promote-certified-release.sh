#!/usr/bin/env bash
# Promote a fully certified source commit to a tag, then dispatch publication
# with a tag ref so the protected release environment can authorize the job.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
[[ $# == 1 ]] || { echo 'Usage: promote-certified-release.sh VERIFIED_DIR' >&2; exit 2; }
dir=$(cd "$1" && pwd)
[[ "${GITHUB_REPOSITORY,,}" == cajeerteam/cajeerengine ]]
[[ "$GITHUB_EVENT_NAME" == push ]]
[[ "$GITHUB_SHA" =~ ^[a-f0-9]{40}$ ]]
[[ "$GITHUB_SHA" == "$(git -C "$root" rev-parse HEAD)" ]] || { echo "Checkout commit does not match event" >&2; exit 1; }
[[ "$GITHUB_RUN_ID" =~ ^[1-9][0-9]*$ ]]
version=$(cat "$root/VERSION")
tag="v$version"
if [[ "$GITHUB_REF" != refs/heads/main && "$GITHUB_REF" != "refs/tags/$tag" ]]; then
  echo 'Promotion is restricted to main and its exact release tag' >&2; exit 1
fi
# This checks the actual source+dist payload bytes, dependency audit, disposable
# host evidence, and the bound checkout SHA (not an untrusted JSON flag alone).
python3 "$root/tools/certification-evidence.py" verify "$dir"
if [[ "$GITHUB_REF" == refs/heads/main ]]; then
  if existing=$(gh api "repos/$GITHUB_REPOSITORY/git/ref/tags/$tag" 2>/dev/null); then
    # Retry only an identical tag; never overwrite or move an existing release.
    type=$(printf '%s' "$existing" | php -r '$j=json_decode(stream_get_contents(STDIN),true,512,JSON_THROW_ON_ERROR);echo $j["object"]["type"];')
    object=$(printf '%s' "$existing" | php -r '$j=json_decode(stream_get_contents(STDIN),true,512,JSON_THROW_ON_ERROR);echo $j["object"]["sha"];')
    if [[ "$type" == tag ]]; then
      object=$(gh api "repos/$GITHUB_REPOSITORY/git/tags/$object" --jq '.object.sha')
    elif [[ "$type" != commit ]]; then
      echo 'Unsupported existing tag object' >&2; exit 1
    fi
    [[ "$object" == "$GITHUB_SHA" ]] || { echo 'Release tag points to another commit' >&2; exit 1; }
  else
    # GitHub GITHUB_TOKEN tag pushes do not trigger a push workflow. Explicit
    # workflow_dispatch below is required to activate the tag-ref publishing job.
    tag_sha=$(gh api --method POST "repos/$GITHUB_REPOSITORY/git/tags" \
      -f "tag=$tag" -f "message=CajeerEngine $version verified release" \
      -f "object=$GITHUB_SHA" -f type=commit --jq .sha)
    gh api --method POST "repos/$GITHUB_REPOSITORY/git/refs" \
      -f "ref=refs/tags/$tag" -f "sha=$tag_sha" >/dev/null
  fi
fi
if gh release view "$tag" --repo "$GITHUB_REPOSITORY" >/dev/null 2>&1; then
  echo "Release $tag already exists; refusing to replace it" >&2; exit 1
fi
# An explicit dispatch can be generated by GITHUB_TOKEN. It uses the tag as
# github.ref; signing remains isolated to the protected release environment.
gh workflow run release-publish.yml --repo "$GITHUB_REPOSITORY" \
  --ref "$tag" -f "certified_run_id=$GITHUB_RUN_ID"
printf 'Dispatched protected publication for %s at %s (certified run %s)\n' "$tag" "$GITHUB_SHA" "$GITHUB_RUN_ID"
